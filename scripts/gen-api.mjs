// Offline stand-in for `npx convex codegen` (which needs a deployment): writes convex/_generated/api.d.ts
// listing every module in convex/. `npx convex deploy` regenerates the real files on every deploy.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = "convex";
const mods = [];
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (f === "_generated" || f.startsWith(".")) continue;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.ts$/.test(f) && !/\.(test|d)\.ts$/.test(f) && !["schema.ts", "auth.config.ts", "convex.config.ts"].includes(f)) mods.push(relative(root, p).replace(/\.ts$/, ""));
  }
})(root);
mods.sort();
const id = (m) => m.replace(/[\/-]/g, "_");
const out = `/* eslint-disable */
/** Generated by scripts/gen-api.mjs (offline). \`npx convex deploy\` regenerates it. */
import type { ApiFromModules, FilterApi, FunctionReference } from "convex/server";
${mods.map((m) => `import type * as ${id(m)} from "../${m}.js";`).join("\n")}

declare const fullApi: ApiFromModules<{
${mods.map((m) => `  ${m.includes("/") ? JSON.stringify(m) : m}: typeof ${id(m)};`).join("\n")}
}>;
export declare const api: FilterApi<typeof fullApi, FunctionReference<any, "public">>;
export declare const internal: FilterApi<typeof fullApi, FunctionReference<any, "internal">>;
export declare const components: {};
`;
writeFileSync(join(root, "_generated", "api.d.ts"), out);
console.log("api.d.ts:", mods.join(", "));
